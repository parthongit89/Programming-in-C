// Multidimensional array 2D

# include <stdio.h>
int main(){
    int arr[0][1] = {{1,2},{3,4}}; // Declaration
    return 0;

    // Access
    arr[0][0]; // --> 1 element
    arr[0][1]; // --> 2 element
    arr[1][0]; // --> 3 element
    arr[1][1]; // --> 4 element
}
